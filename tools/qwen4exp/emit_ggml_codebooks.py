#!/usr/bin/env python3

r"""Emit the GGML quantisation codebooks as a C++ include.

The tables are parsed out of llama.cpp's own `ggml-common.h` rather than retyped: an 8x256 grid of
magic constants is exactly the kind of data a hand copy gets wrong in one place. The generated file
is checked in, so a build does not depend on the upstream tree.

Usage:
  python emit_ggml_codebooks.py \
      --common H:\TeleAgentWorks\.temp\repos\llama-latest\ggml\src\ggml-common.h \
      --out <repo>/src/core/ggml_codebook.inc
"""

from __future__ import annotations

import argparse
import re

# (C++ name, upstream name, element type, element count)
TABLES = [
    ("kIq2xsMask", "kmask_iq2xs", "std::uint8_t", 8),
    ("kIq2xsSigns", "ksigns_iq2xs", "std::uint8_t", 128),
    ("kIq2xxsGrid", "iq2xxs_grid", "std::uint64_t", 256),
    ("kIq2xsGrid", "iq2xs_grid", "std::uint64_t", 512),
    ("kIq2sGrid", "iq2s_grid", "std::uint64_t", 1024),
    ("kIq3xxsGrid", "iq3xxs_grid", "std::uint32_t", 256),
    ("kIq3sGrid", "iq3s_grid", "std::uint32_t", 512),
    ("kIq4nlValues", "kvalues_iq4nl", "std::int8_t", 16),
]


def table_block(text: str, name: str) -> tuple[str, str, int]:
    begin = re.search(rf"GGML_TABLE_BEGIN\(([^,]+),\s*{name},\s*(\d+)\)", text)
    if begin is None:
        raise SystemExit(f"{name}: GGML_TABLE_BEGIN not found")
    kind, count = begin.group(1).strip(), int(begin.group(2))
    start = begin.end()
    end = text.index("GGML_TABLE_END()", start)
    body = text[start:end]
    values = [v.strip() for v in body.replace("\n", " ").split(",") if v.strip()]
    if len(values) != count:
        raise SystemExit(f"{name}: {len(values)} values, header says {count}")
    return kind, values, count


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--common", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    with open(args.common, "r", encoding="utf-8", errors="replace") as f:
        text = f.read()

    lines = [
        "// Generated by tools/qwen4exp/emit_ggml_codebooks.py from llama.cpp's ggml-common.h.",
        "// Do not edit: regenerate instead. Every entry is the upstream codebook verbatim, so a",
        "// decode that disagrees with llama.cpp disagrees because of an algorithm, not a constant.",
        "",
    ]
    for cpp_name, upstream, elem, count in TABLES:
        kind, values, seen = table_block(text, upstream)
        expect = {"uint8_t": "std::uint8_t", "int8_t": "std::int8_t",
                  "uint32_t": "std::uint32_t", "uint64_t": "std::uint64_t"}[kind]
        if expect != elem:
            raise SystemExit(f"{upstream}: header says {kind}, table wants {elem}")
        if seen != count:
            raise SystemExit(f"{upstream}: count mismatch")
        lines.append(f"inline constexpr {elem} {cpp_name}[{count}] = {{")
        for i in range(0, count, 4):
            row = ", ".join(values[i:i + 4])
            lines.append(f"    {row},")
        lines.append("};")
        lines.append("")

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {args.out}: {len(TABLES)} tables")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
