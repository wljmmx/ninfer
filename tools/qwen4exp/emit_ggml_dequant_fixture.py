#!/usr/bin/env python3

r"""Emit a decode fixture: real GGML blocks from a real artifact plus gguf-py's expected values.

`src/core/ggml_dequant.h` is a second, independent implementation of the GGML block formats (that
one is C++, hand-written against llama.cpp's dequantisers). The fixture is the arbiter: it takes the
first blocks of a tensor of every encoding this port carries and records what gguf-py decodes them to,
so a disagreement is caught by a test instead of by a wrong activation much later.

Usage:
  python emit_ggml_dequant_fixture.py \
      --gguf R:\model\qwen4exp\IQ3_XXS\...-00001-of-00002.gguf \
      --blocks 2 --out <repo>/tests/core/ggml_dequant_fixture.h
"""

from __future__ import annotations

import argparse
import sys

sys.path.insert(0, r"H:\TeleAgentWorks\.temp\repos\llama-latest\gguf-py")
import gguf  # noqa: E402
import numpy as np  # noqa: E402

# The encodings this container carries as `ggml_<type>`, in the order the test reports them.
WANTED = ["Q4_K", "Q5_K", "Q6_K", "Q2_0", "IQ4_NL", "IQ4_XS", "IQ2_XXS", "IQ2_XS", "IQ2_S",
          "IQ3_XXS", "IQ3_S"]


def blocks_of(path: str, wanted: list[str], take: int):
    reader = gguf.GGUFReader(path)
    found = {}
    for t in reader.tensors:
        qtype = gguf.GGMLQuantizationType(int(t.tensor_type))
        name = qtype.name
        if name not in wanted or name in found:
            continue
        # gguf-py's table is (elements per block, encoded bytes per block).
        elements, type_bytes = gguf.quants.GGML_QUANT_SIZES[qtype]
        with open(path, "rb") as f:
            f.seek(int(t.data_offset))
            raw = f.read(type_bytes * take)
        if len(raw) != type_bytes * take:
            raise SystemExit(f"{t.name}: short read")
        arranged = np.frombuffer(raw, dtype=np.uint8).reshape(take, type_bytes)
        expected = gguf.quants.dequantize(arranged, qtype).reshape(-1)
        found[name] = (t.name, type_bytes, elements, raw, expected.astype(np.float32))
    missing = [w for w in wanted if w not in found]
    if missing:
        raise SystemExit(f"encodings not present in {path}: {missing}")
    return found


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--gguf", required=True)
    ap.add_argument("--blocks", type=int, default=2)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    found = blocks_of(args.gguf, WANTED, args.blocks)

    lines = [
        "// Generated by tools/qwen4exp/emit_ggml_dequant_fixture.py. Do not edit.",
        "//",
        "// Source tensor blocks from the packed artifact's own GGUF, and the values gguf-py decodes",
        "// them to. gguf-py is an independent implementation of the same block formats, so agreement",
        "// here is evidence about the format rather than about one code path agreeing with itself.",
        "",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace ninfer::test {",
        "",
        "struct GgmlFixture {",
        "    const char* encoding;   // GGML type name, as the container spells it after `ggml_`",
        "    const char* source;     // the tensor these blocks came from",
        "    std::uint64_t block;    // values per encoded block",
        "    std::uint64_t type_bytes;",
        "    const std::uint8_t* data;",
        "    std::size_t bytes;",
        "    const float* expected;",
        "    std::size_t elements;",
        "};",
        "",
    ]
    for name in WANTED:
        source, type_bytes, elements, raw, expected = found[name]
        lines.append(f"// {name} from {source} ({elements} values/block, {type_bytes} bytes/block)")
        lines.append(f"inline constexpr std::uint8_t k{name}Data[{len(raw)}] = {{")
        for i in range(0, len(raw), 16):
            row = ", ".join(f"0x{b:02x}" for b in raw[i:i + 16])
            lines.append(f"    {row},")
        lines.append("};")
        lines.append(f"inline constexpr float k{name}Expected[{len(expected)}] = {{")
        for i in range(0, len(expected), 4):
            row = ", ".join(float(v).hex() for v in expected[i:i + 4])
            lines.append(f"    {row},")
        lines.append("};")
        lines.append("")

    lines.append("inline constexpr GgmlFixture kGgmlFixtures[] = {")
    for name in WANTED:
        source, type_bytes, elements, raw, expected = found[name]
        lines.append(f'    {{"{name}", "{source}", {elements}, {type_bytes}, k{name}Data, '
                     f"sizeof(k{name}Data), k{name}Expected, {len(expected)}}},")
    lines.append("};")
    lines.append("")
    lines.append("} // namespace ninfer::test")
    lines.append("")

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {args.out}: {len(WANTED)} encodings, "
          f"{sum(len(found[n][3]) for n in WANTED)} block bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
